#!/usr/bin/env bash
# Derive this worktree's isolated environment and write it to .env (gitignored).
#
# Every worktree gets its own compose project name and its own block of ports,
# derived deterministically from the worktree's absolute path (orca_derive_env
# in lib.sh) -- stable across restarts, never colliding between worktrees. On
# top of the ports go what this project's tests and build read: the RomM
# version, the three BASE_URLs and the two shared caches. Every
# generate-if-missing (compose.sh, seed.sh, tls-fixture.sh) calls this script.
# See docs/TESTING.md and the Q8 decision in docs/DEVELOPMENT.md#worktree-isolation.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$REPO_ROOT"
. ./scripts/orca/lib.sh

# Which RomM the fixture runs (#227). The caller's environment wins, so
# `ROMM_VERSION=5.4.0 ./scripts/orca/env.sh` is how a worktree moves; otherwise
# whatever .env already said, because compose.sh and seed.sh regenerate this
# file on their own and must not quietly move a worktree back. The default is
# the one server/testing/docker-compose.yml falls back to, and the two move
# together (`orca.env_romm_version`). 5.4.0 since #235, and the floor too:
# `rig.version_live` fails a .env that names anything older, because a .env
# written before #235 says 5.2.0 only because that was the default then.
ROMM_VERSION_DEFAULT=5.4.0
romm_version="${ROMM_VERSION:-}"
if [ -z "$romm_version" ] && [ -f .env ]; then
  romm_version="$(sed -n 's/^ROMM_VERSION=//p' .env | head -1)"
fi
romm_version="${romm_version:-$ROMM_VERSION_DEFAULT}"

orca_derive_env "$REPO_ROOT" \
  || { echo "no sha1 tool (shasum/sha1sum/python3); cannot name this worktree's stack" >&2; exit 1; }

# Shared across worktrees on purpose: immutable, expensive to refetch. Mutable
# state (RomM's database volume, build output) stays per-worktree.
ROM_CACHE="$REPO_ROOT/.cache/roms"
CCACHE_DIR="$REPO_ROOT/.cache/ccache"
mkdir -p "$ROM_CACHE" "$CCACHE_DIR"

# A private temp file per run, not a shared `.env.tmp`: compose.sh generates a
# missing .env itself, so there can be two writers at the same moment, and
# sharing one temp path let the first `mv` carry off the second's source file.
ORCA_ENV_TMP="$(mktemp "$REPO_ROOT/.env.tmp.XXXXXX")"
trap 'rm -f "$ORCA_ENV_TMP"' EXIT
{
  echo "# Generated by scripts/orca/env.sh -- do not commit, do not hand-edit."
  echo "# Regenerate with: ./scripts/orca/env.sh"
  echo "COMPOSE_PROJECT_NAME=$orca_project"
  # The FLEET_* names predate this script and are kept so a running worktree's
  # .env reads the same after #277; the offset lets a rig that needs one more
  # port derive it without a second numbering scheme.
  echo "FLEET_PROJECT=$orca_project"
  echo "FLEET_SLUG=$orca_slug"
  echo "FLEET_OFFSET=$orca_offset"
  echo "ROMM_PORT=$orca_romm_port"
  echo "PROXY_PORT=$orca_proxy_port"
  echo "TLS_PORT=$orca_tls_port"
  echo "ROMM_VERSION=$romm_version"
  echo "ROMM_BASE_URL=http://127.0.0.1:$orca_romm_port"
  echo "PROXY_BASE_URL=http://127.0.0.1:$orca_proxy_port"
  echo "TLS_BASE_URL=https://127.0.0.1:$orca_tls_port"
  echo "ROM_CACHE=$ROM_CACHE"
  echo "CCACHE_DIR=$CCACHE_DIR"
} > "$ORCA_ENV_TMP"
# Atomically, because compose.sh sources .env unguarded and may be reading at
# this moment; a read landing inside a truncating rewrite sees no
# COMPOSE_PROJECT_NAME and docker-compose.yml falls back to `rmx-local`.
# Concurrent writers are safe too: the derivation is a pure function of the
# worktree path, so whichever rename lands last publishes the same content.
mv -f "$ORCA_ENV_TMP" "$REPO_ROOT/.env"

echo "worktree env: project=$orca_project romm=$romm_version@$orca_romm_port proxy=$orca_proxy_port tls=$orca_tls_port"
